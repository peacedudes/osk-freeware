#!/usr/bin/env python3
"""Regenerate disk/DOC/DEPENDS by scanning every command binary for paths.

    tools/gen_depends.py disk            # rewrite disk/DOC/DEPENDS
    tools/gen_depends.py disk --check    # exit 1 if it would change

DEPENDS answers "what else does this program need?", which matters because
copying one command onto a disk of your own usually is not enough. The
answer is derived, not curated: a program's binary carries the absolute
paths it will open, so scanning for them is the only account that stays
true after the tree changes. It had drifted from being edited by hand.

What counts as a dependency:

  * A path under /dd or /h0, case-insensitively -- those are the two devices
    the collection is meant to be arranged as. Paths to anywhere else (larn's
    /d0/sys/termcap and /tmp/#%dmail600, say) are a different machine's
    layout and are left out; listing them would imply this disk should
    provide them.
  * EVERY occurrence, including one inside another. X11R6shl carries the
    string /h0/X11R5/X11/h0/usr/local/include, which yields both itself and
    /h0/usr/local/include -- either could be what the program actually opens,
    and the scan cannot tell.

A path is marked '--' when nothing answers to it on this disk. OS-9 matching
is case-insensitive, so /h0/games/hack/playground finds GAMES/HACK/playground
and is NOT marked. Getting that wrong would flag most of the disk as missing.

The scan cannot tell a file the program READS from one it CREATES at runtime,
so both appear; the header says so.
"""
import os, re, sys

# EVERY DIRECTORY THAT HOLDS PROGRAMS.  This was CMDS and CMDS/GAMES alone
# until 2026-08-29, which left 354 programs -- a third of the disk, the
# whole of NETPBM, UUCP, ELM, TEXCMDS and the rest -- with no entry at all
# in a file whose first line promises "what each program needs".  The same
# gap was found in gen_catalog.py twice before; the list is kept identical
# to the one there.  CMDS/archives stays out: it holds .lzh source
# archives, not programs.
SCAN_DIRS = ["CMDS", "CMDS/GAMES", "CMDS/NETPBM",
             "CMDS/REBUILT", "CMDS/GCC139", "CMDS/GCC2", "CMDS/GCC137", "CMDS/GCC272", "CMDS/DRIVERS", "CMDS/X68K", "CMDS/SYSADMIN", "CMDS/DEMOS",
             "CMDS/DHRY", "CMDS/MM1", "CMDS/UUCP", "CMDS/ADL",
             "CMDS/COMMS", "CMDS/ELM", "CMDS/NETWORK", "CMDS/NEWS",
             "CMDS/TEXCMDS", "CMDS/WN"]
DEVICES   = ("dd", "h0")
PATH_CHAR = rb"[A-Za-z0-9_./]"
PATH_RE   = re.compile(rb"/(?:" + b"|".join(
                d.encode() for d in DEVICES) + rb")/" + PATH_CHAR + b"+",
              re.IGNORECASE)
COLUMN    = 53          # where the '--' marker sits; matches the original
MISSING   = "--"

HEADER = """DEPENDS -- what each program needs besides its own binary
=========================================================

Generated by scanning every binary for absolute OS-9 paths.  Use it when
copying individual programs onto a disk of your own: the binary alone is
often not enough.

A path listed here may be a file the program READS (copy it too) or one it
CREATES at runtime (make sure the directory exists and is writable).  The
scan cannot tell those apart, so both are listed.  '--' marks a path not on
this disk: either the program creates it, or its data was never collected.

A THIRD case, measured 2026-08-20 and easy to mistake for a fault: many of
these are FALLBACK paths compiled into the binary that the program never
actually opens.  Nineteen mtools programs list /dd/sys/mtools as missing and
every one of them works, because they read /dd/sys/mtools.conf, which is
here.  The same is true of /dd/SYS/errmsg.short, /dd/SYS/utmp and /dd/TEMP --
`env', `expr' and `cjpeg' all list one of those and all run.
So a `--' here is NOT evidence that a program is broken.  Run it and see.

Most entries are /h0/sys/termcap -- %d programs want termcap at that exact
path.  DOC/README-RUNNING explains how to arrange /h0.

--------------------------------------------------------------
"""


def paths_in(binary):
    """Every /dd or /h0 path in one file, deduped, in order of first appearance.

    NOT sorted. The order a program's paths sit in its binary tends to group
    the ones it uses together -- beav's /dd/sys and /h0/sys arrive before the
    two termcaps under them -- and sorting scatters that. It is deterministic
    either way, so the more informative order wins.

    Overlapping matches are wanted, so each search restarts one byte past the
    previous match's START rather than at its end: X11R6shl carries
    /h0/X11R5/X11/h0/usr/local/include, which must also yield the
    /h0/usr/local/include sitting inside it.
    """
    data  = open(binary, "rb").read()
    seen, order, pos = set(), [], 0
    while True:
        m = PATH_RE.search(data, pos)
        if not m:
            break
        found = m.group().decode("ascii")
        # AN RCS FILE NAME IS NOT A FILE THE PROGRAM OPENS.  hdump carries
        # its builder's `/dd/USR/.../rcs/od.c_v' in an RCS $Header$ string,
        # and the card listed it as something hdump needs (2026-09-26).
        if re.search(r"/rcs/[^/]*[_,]v$", found, re.I):
            pos = m.start() + 1
            continue
        if found not in seen:
            seen.add(found)
            order.append(found)
        pos = m.start() + 1
    return order


def resolve(root, path):
    """True if `path` (a /dd or /h0 path) names something on the disk.

    Walked one component at a time with a case-insensitive comparison,
    because OS-9 matches that way and the disk's own names disagree in case
    with what many binaries ask for.
    """
    here = root
    for part in path.strip("/").split("/")[1:]:      # drop the device
        if not part:
            continue
        try:
            match = next((e for e in sorted(os.listdir(here)) if e.lower() == part.lower()), None)
        except (NotADirectoryError, PermissionError, FileNotFoundError):
            return False
        if match is None:
            return False
        here = os.path.join(here, match)
    return True


def survey(root):
    """[(program, dir_label, [(path, present), ...]), ...] for programs with paths."""
    out = []
    for d in SCAN_DIRS:
        full = os.path.join(root, d)
        if not os.path.isdir(full):
            continue
        for name in sorted(os.listdir(full)):
            binary = os.path.join(full, name)
            if not os.path.isfile(binary):
                continue
            found = paths_in(binary)
            if found:
                out.append((name, d, [(p, resolve(root, p)) for p in found]))
    out.sort(key=lambda e: e[0])                     # by name, case-sensitive
    return out


BARE_HEADER = """
--------------------------------------------------------------

AND THE HALF A PATH SCAN CANNOT SEE
-----------------------------------

Everything above was found by looking for ABSOLUTE paths.  A program that
opens `kepler.dat' rather than `/h0/kepler.dat' does not appear there at
all -- and opening a data file by BARE NAME, relative to the process's
DATA DIRECTORY, is the ordinary thing for a program of this era to do.

Two programs were written up in DOC/STATUS as broken for want of exactly
this.  `orbit' "wanted an element file no archive here carried"; it is in
DOC/orbit, and orbit opens it by bare name.  `advcom' "needed a shell with
a real chd"; it needs its include where the data directory already is,
which is not the same thing.  Both work.

So: below is every module that names a file with NO SLASH IN IT where a
file of that name is somewhere on this disk.  To use one of these
programs, put the file where your data directory is:

    cat /dd/DOC/orbit/kepler.dat > /dd/kepler.dat
    orbit

THIS SECTION PROVES NOTHING.  A string in a binary may be a message, or a
filename the compiler baked in; and a file of the right name elsewhere on
the disk may not be the file the program wants.  Read it as a list of
things to try.  It lists only names whose extension suggests DATA -- the
full sweep, including source extensions, is `tools/bare_deps.py --all'.

"""


def render_bare(root):
    """The bare-name section, or "" if the scanner is not importable."""
    try:
        sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
        import bare_deps
    except ImportError:
        return ""
    rows = bare_deps.scan(root)
    if not rows:
        return ""
    body = BARE_HEADER.split("\n")
    last = None
    for prog, name, where in rows:
        if prog != last:
            body.append("  %s" % prog)
            last = prog
        line = "      %s" % name
        line += " " * max(COLUMN - len(line) - 8, 1)
        body.append(line + "-> " + where)
    body.append("")
    return "\r".join(body)


def render(entries):
    termcap = sum(1 for _, _, ps in entries
                  for p, _ in ps if p.lower() == "/h0/sys/termcap")
    # HEADER is written with ordinary newlines for legibility in this file;
    # split it so every line joins with CR like the rest. An LF that reaches
    # the disk makes OS-9's cpp read the whole file as one line.
    body = (HEADER % termcap).split("\n")   # trailing \n leaves the blank line
    for name, where, paths in entries:
        body.append("  %s   (%s)" % (name, where))
        for path, present in paths:
            line = "      " + path
            line += " " * max(COLUMN - len(line), 1)
            body.append(line if present else line + MISSING)
        body.append("")
    text = "\r".join(body) + "\r"
    assert "\n" not in text, "refusing to emit LF into an OS-9 text file"
    return text


if __name__ == "__main__":
    args  = [a for a in sys.argv[1:] if not a.startswith("-")]
    check = "--check" in sys.argv
    if len(args) != 1:
        raise SystemExit("usage: gen_depends.py <disk-tree> [--check]")
    root = args[0]
    if not os.path.isdir(os.path.join(root, "CMDS")):
        raise SystemExit("not a disk tree (no CMDS): %s" % root)

    entries = survey(root)
    text    = render(entries) + render_bare(root)
    target  = os.path.join(root, "DOC", "DEPENDS")

    if check:
        current = open(target, "rb").read().decode("latin-1")
        if current == text:
            print("  DOC/DEPENDS is up to date")
            raise SystemExit(0)
        print("  DOC/DEPENDS is STALE -- run tools/gen_depends.py %s" % root)
        raise SystemExit(1)

    open(target, "wb").write(text.encode("latin-1"))
    print("  %s: %d programs, %d paths"
          % (target, len(entries), sum(len(p) for _, _, p in entries)))
